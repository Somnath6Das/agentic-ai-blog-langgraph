import {
  View,
  Text,
  ScrollView,
  RefreshControl,
  TouchableOpacity,
  StyleSheet,
  Platform,
  StatusBar,
} from "react-native";
import React, { useCallback, useEffect, useState } from "react";
import { useMenuStore } from "@/store/blog_store";
import { useRouter } from "expo-router";
import useAuthStore from "@/store/auth_store";
import { Blog, getPublicBlogs } from "@/utils/get_public_blogs";
import axios from "axios";
import { SafeAreaView } from "react-native-safe-area-context";
import Animated, { FadeInDown } from "react-native-reanimated";
import FeaturedCarousel from "@/components/home/FeaturedCarousel";
import PostCard from "@/components/home/PostCard";
import { FONTS } from "@/constants/theme";

let hasPlayedIntroAnimation = false;

export default function HomeScreen() {
  const setTotalPublishedBlog = useMenuStore((s) => s.setTotalPublishedBlog);
  const setTotalGeneratedBlog = useMenuStore((s) => s.setTotalGeneratedBlog);

  const router = useRouter();
  const addMenuItem = useMenuStore((s) => s.addMenuItem);
  const menuItems = useMenuStore((s) => s.menuItems);
  const { user, clearAuth } = useAuthStore();
  const [blogs, setBlogs] = useState<Blog[]>([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Decide once, on first mount of this instance, whether to animate.
  const [shouldAnimate] = useState(() => {
    if (hasPlayedIntroAnimation) return false;
    hasPlayedIntroAnimation = true;
    return true;
  });
  const fetchBlogs = async () => {
    try {
      const data = await getPublicBlogs();

      setBlogs(data);
      // console.log(data);
      setError(null);
      //  total user blogs
      const userBlogs = data.filter(
        (blog) => String(blog.user_id) === String(user?.id),
      );
      //number of total published blog by the user
      setTotalPublishedBlog(userBlogs.length);

      const existingPostIds = new Set(
        menuItems
          .map((item) => item.id)
          .filter((id) => id !== undefined)
          .map(String),
      );

      const newBlogs = userBlogs.filter(
        (blog) => !existingPostIds.has(String(blog.post_id)),
      );
      //number of total blog generated by the user
      setTotalGeneratedBlog(menuItems.length);

      // newBlogs.forEach((blog) => {
      //   addMenuItem({
      //     user_topic: "",
      //     title: blog.title,
      //     file_path: blog.html_path,
      //     images: blog.image ? [blog.image] : [],
      //   });
      // });
    } catch (err) {
      setError(
        axios.isAxiosError(err)
          ? (err.response?.data?.detail ?? "Failed to load blogs")
          : "Something went wrong",
      );
      console.error(err);
    }
  };
  useEffect(() => {
    if (!user?.id) return; // wait for hydration
    (async () => {
      setLoading(true);
      await fetchBlogs();
      setLoading(false);
    })();
  }, [user?.id]);

  const onRefresh = useCallback(async () => {
    setRefreshing(true);
    await fetchBlogs();
    setRefreshing(false);
  }, []);
  return (
    <SafeAreaView style={styles.safe}>
      <ScrollView
        contentContainerStyle={styles.scroll}
        showsVerticalScrollIndicator={false}
        refreshControl={
          <RefreshControl refreshing={refreshing} onRefresh={onRefresh} />
        }
      >
        {/* Header */}
        <Animated.View
          entering={
            shouldAnimate ? FadeInDown.duration(400).delay(50) : undefined
          }
          style={styles.header}
        >
          <Text style={styles.brand}>INFODOOR</Text>
        </Animated.View>

        {/* Journal heading */}
        <Animated.Text
          entering={
            shouldAnimate ? FadeInDown.duration(400).delay(100) : undefined
          }
          style={styles.sectionTitle}
        >
          Journal
        </Animated.Text>

        {/* Carousel — all posts */}
        <Animated.View
          entering={
            shouldAnimate ? FadeInDown.duration(500).delay(150) : undefined
          }
        >
          <FeaturedCarousel posts={blogs} />
        </Animated.View>

        {/* Popular header */}
        <Animated.View
          entering={
            shouldAnimate ? FadeInDown.duration(400).delay(220) : undefined
          }
          style={styles.popularHeader}
        >
          <Text style={styles.sectionTitle}>Latest</Text>
          <TouchableOpacity onPress={() => router.push("/post/show_all")}>
            <Text style={styles.showAll}>Show all</Text>
          </TouchableOpacity>
        </Animated.View>

        {/* Popular list */}
        {blogs.slice(0, 5).map((post, idx) => (
          <Animated.View
            key={post.id}
            entering={
              shouldAnimate
                ? FadeInDown.duration(400).delay(280 + idx * 80)
                : undefined
            }
          >
            <PostCard post={post} />
          </Animated.View>
        ))}

        <View style={styles.bottomSpacer} />
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  safe: {
    flex: 1,
    backgroundColor: "#fff",
    paddingTop: Platform.OS === "android" ? (StatusBar.currentHeight ?? 0) : 0,
  },
  header: {
    flexDirection: "row",
    alignItems: "center",
    paddingHorizontal: 16,
    paddingVertical: 8,
  },
  brand: {
    flex: 1,
    ...FONTS.displayMD,
    fontSize: 20,
    color: "#E8622A",
    justifyContent: "center",
    textAlign: "center",
    letterSpacing: 2,
  },
  avatar: {
    width: 32,
    height: 32,
    borderRadius: 16,
    backgroundColor: "#C4C4C4",
  },
  scroll: {
    paddingHorizontal: 16,
    paddingTop: 8,
  },
  sectionTitle: {
    ...FONTS.displayLG,
    color: "#1A1A1A",
    marginBottom: 16,
  },
  popularHeader: {
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "space-between",
    marginBottom: 16,
  },
  showAll: {
    fontSize: 12,
    fontWeight: "500",
    color: "#E8622A",
  },
  bottomSpacer: {
    height: 24,
  },
});
